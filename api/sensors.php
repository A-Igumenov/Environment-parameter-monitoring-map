// ─────────────────────────────────────────────────────────
// 4.3 GET stream — Server-Sent Events (SSE) realaus laiko atnaujinimai.
//     Instead of 30s polling, the browser keeps an open connection and gets new
//     map_data every few seconds. Sends only when data changes
//     (based on the latest recorded_at) — saves bandwidth.
// ─────────────────────────────────────────────────────────
if ($action === 'stream') {
    // CRITICAL: release the session lock IMMEDIATELY. PHP sessions are
    // file-locked — while SSE keeps the session open, ALL other requests
    // of the same user (pages, forms, API) block
    // waiting for the lock. session_write_close() releases the lock but
    // leaves the $_SESSION data readable in this process.
    if (session_status() === PHP_SESSION_ACTIVE) {
        session_write_close();
    }

    // SSE headers
    header('Content-Type: text/event-stream');
    header('Cache-Control: no-cache');
    header('Connection: keep-alive');
    header('X-Accel-Buffering: no'); // disable nginx buffering

    @set_time_limit(0);
    ignore_user_abort(false);

    // Function for assembling map_data (same logic as the map_data endpoint)
    $fetchMapData = function (): array {
        $sql = "
            SELECT s.id,
                CONCAT(s.city_prefix, (
                    SELECT COUNT(*) FROM sensors s2
                    WHERE s2.city_prefix = s.city_prefix AND s2.id <= s.id
                )) AS label,
                s.lat, s.lng, s.mac, s.is_outdoor, s.last_seen,
                CASE WHEN s.last_seen >= DATE_SUB(NOW(), INTERVAL :tmin MINUTE)
                     THEN 1 ELSE 0 END AS online,
                r.temperature, r.humidity, r.co2, r.pm1, r.pm2_5,
                r.pm10, r.grains, r.radiation,
                r.alcohol, r.methane, r.propane, r.butane, r.lpg, r.hydrogen,
                r.co, r.smoke, r.ammonia, r.nox, r.benzene, r.air_quality, r.co2_equiv,
                r.recorded_at
            FROM sensors s
            LEFT JOIN readings r ON r.id = (
                SELECT id FROM readings WHERE sensor_id = s.id
                ORDER BY recorded_at DESC LIMIT 1
            )
            WHERE s.confirmed = 1
            ORDER BY s.id ASC
        ";
        $stmt = db()->prepare($sql);
        $stmt->execute([':tmin' => SENSOR_TIMEOUT_MIN]);
        $sensors = $stmt->fetchAll();
        foreach ($sensors as &$s) {
            $s['lat'] = (float)$s['lat'];
            $s['lng'] = (float)$s['lng'];
            $s['last_seen']   = toIsoUtc($s['last_seen'] ?? null);
            $s['recorded_at'] = toIsoUtc($s['recorded_at'] ?? null);
        }
        unset($s);
        return $sensors;
    };

    // Last-change marker (so we send only on change)
    $lastHash = '';
    $iterations = 0;
    $maxIterations = 720; // ~1 h (every 5s) — then the browser switches automatically

    while ($iterations < $maxIterations) {
        if (connection_aborted()) break;

        try {
            $sensors = $fetchMapData();
            $hash = md5(json_encode($sensors));

            // Send only if the data changed (or the first time)
            if ($hash !== $lastHash) {
                $lastHash = $hash;
                echo "event: update\n";
                echo 'data: ' . json_encode([
                    'sensors' => $sensors,
                    'count'   => count($sensors),
                    'ts'      => date('c'),
                ]) . "\n\n";
            } else {
                // Heartbeat (comment) so the connection stays open
                echo ": heartbeat\n\n";
            }
        } catch (\Throwable $e) {
            echo "event: error\n";
            echo 'data: ' . json_encode(['error' => 'stream_error']) . "\n\n";
        }

        if (ob_get_level() > 0) @ob_flush();
        @flush();

        sleep(5); // check every 5 seconds
        $iterations++;
    }
    // On reaching the limit — tell the client the connection ended cleanly.
    // The client will switch to polling instead of reconnecting endlessly.
    echo "event: bye\n";
    echo "data: {\"reason\":\"max_duration\"}\n\n";
    if (ob_get_level() > 0) @ob_flush();
    @flush();
    exit;
}

if ($action === 'map_data') {
    // ALL confirmed sensors are shown — online and offline.
    // online  = last_seen <= SENSOR_TIMEOUT_MIN min atgal
    // offline = last_seen >  SENSOR_TIMEOUT_MIN min ago (silent, but history kept)

    // 4.1 Viewport (bbox) filtering + pagination for high density.
    // If sw_lat/sw_lng/ne_lat/ne_lng are provided — return only those in that
    // bounding box. limit/offset for pagination.
    $bboxSql = '';
    $bboxParams = [];
    $swLat = getFloat('sw_lat', -90, 90);
    $swLng = getFloat('sw_lng', -180, 180);
    $neLat = getFloat('ne_lat', -90, 90);
    $neLng = getFloat('ne_lng', -180, 180);
    if ($swLat !== null && $swLng !== null && $neLat !== null && $neLng !== null) {
        $bboxSql = " AND s.lat BETWEEN :swlat AND :nelat AND s.lng BETWEEN :swlng AND :nelng";
        $bboxParams = [
            ':swlat' => $swLat, ':nelat' => $neLat,
            ':swlng' => $swLng, ':nelng' => $neLng,
        ];
    }

    // Pagination (optional). limit 0 or unspecified = all.
    $limit  = max(0, min(50000, (int)($_GET['limit'] ?? 0)));
    $offset = max(0, (int)($_GET['offset'] ?? 0));
    $limitSql = $limit > 0 ? " LIMIT $limit OFFSET $offset" : '';

    $sql = "
        SELECT
            s.id,
            CONCAT(s.city_prefix, (
                SELECT COUNT(*) FROM sensors s2
                WHERE s2.city_prefix = s.city_prefix AND s2.id <= s.id
            )) AS label,
            s.city_prefix,
            s.lat, s.lng, s.mac, s.is_outdoor,
            (s.secret IS NOT NULL) AS has_secret,
            s.registered_at, s.last_seen,
            CASE
                WHEN s.last_seen >= DATE_SUB(NOW(), INTERVAL :tmin MINUTE)
                THEN 1 ELSE 0
            END AS online,
            r.temperature, r.humidity, r.co2,
            r.pm1, r.pm2_5, r.pm10, r.grains, r.radiation,
            r.alcohol, r.methane, r.propane, r.butane, r.lpg, r.hydrogen,
            r.co, r.smoke, r.ammonia, r.nox, r.benzene, r.air_quality, r.co2_equiv,
            r.recorded_at
        FROM sensors s
        LEFT JOIN readings r ON r.id = (
            SELECT id FROM readings
            WHERE sensor_id = s.id
            ORDER BY recorded_at DESC
            LIMIT 1
        )
        WHERE s.confirmed = 1{$bboxSql}
        ORDER BY s.id ASC{$limitSql}
    ";
    $stmt = db()->prepare($sql);
    $stmt->execute(array_merge([':tmin' => SENSOR_TIMEOUT_MIN], $bboxParams));
    $sensors = $stmt->fetchAll();

    $counts = [];
    foreach (db()->query(
        "SELECT sensor_id, COUNT(*) AS n FROM readings GROUP BY sensor_id"
    )->fetchAll() as $row) {
        $counts[$row['sensor_id']] = (int)$row['n'];
    }

    foreach ($sensors as &$s) {
        $s['lat']           = (float)$s['lat'];
        $s['lng']           = (float)$s['lng'];
        $s['reading_count'] = $counts[$s['id']] ?? 0;
        $s['has_secret']    = (int)($s['has_secret'] ?? 0); // HMAC enabled flag (secret never exposed)
        // Time fields → ISO 8601 UTC (with "Z") so the browser converts to local time
        $s['last_seen']     = toIsoUtc($s['last_seen'] ?? null);
        $s['registered_at'] = toIsoUtc($s['registered_at'] ?? null);
        $s['recorded_at']   = toIsoUtc($s['recorded_at'] ?? null);
    }
    unset($s);

    // Total number of confirmed sensors (for pagination)
    $total = (int)db()->query("SELECT COUNT(*) FROM sensors WHERE confirmed = 1")->fetchColumn();

    jsonResponse([
        'sensors'  => $sensors,
        'count'    => count($sensors),
        'total'    => $total,
        'bbox'     => $bboxSql !== '',
        'paginated'=> $limit > 0,
    ]);
}

