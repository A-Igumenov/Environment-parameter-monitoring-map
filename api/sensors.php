/**
 * 2.2 Audit log entry (sensitive admin actions).
 */
function auditLog(string $action, ?int $targetId = null, ?string $details = null): void {
    try {
        db()->prepare(
            "INSERT INTO audit_log (actor_ip, action, target_id, details)
             VALUES (:ip, :action, :tid, :details)"
        )->execute([
            ':ip' => clientIpApi(), ':action' => $action,
            ':tid' => $targetId, ':details' => $details,
        ]);
    } catch (PDOException) { /* sena schema — tyliai praleisti */ }
}

/**
 * Safely splits "1,2,3" into a unique array of positive integer IDs.
 * Limits to 1000 elements (protection against an oversized request).
 */
function parseIdList(string $raw): array {
    $ids = [];
    foreach (explode(',', $raw) as $part) {
        $n = (int)trim($part);
        if ($n > 0) $ids[$n] = true; // raktas = dedupe
    }
    return array_slice(array_keys($ids), 0, 1000);
}

