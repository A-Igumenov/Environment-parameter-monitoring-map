if ($action === 'history') {
    $id = (int)($_POST['id'] ?? $_GET['id'] ?? 0);
    if ($id <= 0) jsonResponse(['error' => 'Trūksta arba neteisingas id'], 400);

    // Whitelisted periods → [hours back, bucket seconds (0 = raw points)].
    // Long ranges are averaged into time buckets so a year-long chart returns
    // a few hundred points instead of tens of thousands.
    $periods = [
        '1d'   => [24,    0],       // 1 diena  — raw
        '1w'   => [168,   3600],    // 1 savaitė — 1 h buckets  (~168 pts)
        '2w'   => [336,   7200],    // 2 savaitės — 2 h buckets (~168 pts)
        '1mo'  => [720,   21600],   // 1 mėnuo  — 6 h buckets   (~120 pts)
        '3mo'  => [2160,  86400],   // 3 mėnesiai — 1 d buckets (~90 pts)
        '6mo'  => [4320,  86400],   // 6 mėnesiai — 1 d buckets (~180 pts)
        '12mo' => [8760,  86400],   // 12 mėnesių — 1 d buckets (~365 pts)
    ];
    $period = (string)($_GET['period'] ?? $_POST['period'] ?? '1d');
    if (!isset($periods[$period])) $period = '1d';
    [$hours, $bucket] = $periods[$period];

    if ($bucket > 0) {
        // $bucket is a whitelisted integer constant → safe to inline.
        $bs = (int)$bucket;
        $stmt = db()->prepare("
            SELECT FROM_UNIXTIME(FLOOR(UNIX_TIMESTAMP(recorded_at)/$bs)*$bs) AS recorded_at,
                   ROUND(AVG(temperature),2) AS temperature,
                   ROUND(AVG(humidity),2)    AS humidity,
                   ROUND(AVG(co2),1)         AS co2,
                   ROUND(AVG(pm1),2)         AS pm1,
                   ROUND(AVG(pm2_5),2)       AS pm2_5,
                   ROUND(AVG(pm10),2)        AS pm10,
                   ROUND(AVG(grains),2)      AS grains,
                   ROUND(AVG(radiation),4)   AS radiation,
                   ROUND(AVG(alcohol),2)     AS alcohol,
                   ROUND(AVG(methane),2)     AS methane,
                   ROUND(AVG(propane),2)     AS propane,
                   ROUND(AVG(butane),2)      AS butane,
                   ROUND(AVG(lpg),2)         AS lpg,
                   ROUND(AVG(hydrogen),2)    AS hydrogen,
                   ROUND(AVG(co),2)          AS co,
                   ROUND(AVG(smoke),2)       AS smoke,
                   ROUND(AVG(ammonia),2)     AS ammonia,
                   ROUND(AVG(nox),2)         AS nox,
                   ROUND(AVG(benzene),2)     AS benzene,
                   ROUND(AVG(air_quality),2) AS air_quality,
                   ROUND(AVG(co2_equiv),2)   AS co2_equiv
            FROM readings
            WHERE sensor_id = :id
              AND recorded_at >= DATE_SUB(NOW(), INTERVAL :h HOUR)
            GROUP BY FLOOR(UNIX_TIMESTAMP(recorded_at)/$bs)
            ORDER BY recorded_at ASC
        ");
    } else {
        $stmt = db()->prepare("
            SELECT recorded_at,
                   temperature, humidity, co2,
                   pm1, pm2_5, pm10, grains, radiation,
                   alcohol, methane, propane, butane, lpg, hydrogen,
                   co, smoke, ammonia, nox, benzene, air_quality, co2_equiv
            FROM readings
            WHERE sensor_id = :id
              AND recorded_at >= DATE_SUB(NOW(), INTERVAL :h HOUR)
            ORDER BY recorded_at ASC
        ");
    }
    $stmt->execute([':id' => $id, ':h' => $hours]);
    $points = $stmt->fetchAll();
    // recorded_at → ISO 8601 UTC (with "Z") so chart times are shown in
    // the user's local time (the browser converts via toLocaleString)
    foreach ($points as &$p) {
        $p['recorded_at'] = toIsoUtc($p['recorded_at'] ?? null);
    }
    unset($p);

    jsonResponse(['sensor_id' => $id, 'period' => $period, 'hours' => $hours, 'points' => $points]);
}

// ─────────────────────────────────────────────────────────
// GET averages — averaged metric values over a chosen time period,
//   respecting the region (city_prefix) and indoor/outdoor filters.
//     period   = 4h|6h|12h|24h|7d|30d|90d|180d|365d|all
//     region   = city_prefix (e.g. "VLN") or "all"
//     location = all|indoor|outdoor
//   "all" = from the very first reading (first sensor start).
// ─────────────────────────────────────────────────────────
if ($action === 'averages') {
    // Whitelisted period → MySQL interval (value + unit). Values are constants,
    // so they are safe to interpolate; user input is matched against the keys.
    $periods = [
        '4h'  => [4,   'HOUR'], '6h'   => [6,   'HOUR'], '12h'  => [12,  'HOUR'],
        '24h' => [24,  'HOUR'], '7d'   => [7,   'DAY'],  '30d'  => [30,  'DAY'],
        '90d' => [90,  'DAY'],  '180d' => [180, 'DAY'],  '365d' => [365, 'DAY'],
    ];
    $period = (string)($_GET['period'] ?? '24h');
    if ($period !== 'all' && !isset($periods[$period])) $period = '24h';

    $where  = ['s.confirmed = 1'];
    $params = [];

    // Region (city_prefix) — same values as the map's region filter.
    $region = strtoupper(trim((string)($_GET['region'] ?? 'all')));
    if ($region !== '' && $region !== 'ALL' && preg_match('/^[A-Z0-9]{1,10}$/', $region)) {
        $where[] = 's.city_prefix = :region';
        $params[':region'] = $region;
    }

    // Indoor / outdoor — mirrors the map's location filter.
    $location = strtolower(trim((string)($_GET['location'] ?? 'all')));
    if ($location === 'indoor')  $where[] = 's.is_outdoor = 0';
    if ($location === 'outdoor') $where[] = 's.is_outdoor = 1';

    // Time window ('all' = no lower bound).
    if ($period !== 'all') {
        [$n, $unit] = $periods[$period];
        $where[] = "r.recorded_at >= DATE_SUB(NOW(), INTERVAL $n $unit)";
    }

    $metrics = ['temperature', 'humidity', 'co2', 'pm1', 'pm2_5', 'pm10', 'grains', 'radiation',
                'alcohol', 'methane', 'propane', 'butane', 'lpg', 'hydrogen', 'co', 'smoke',
                'ammonia', 'nox', 'benzene', 'air_quality', 'co2_equiv'];
    $selects = [];
    foreach ($metrics as $m) {
        $selects[] = "AVG(r.$m) AS {$m}_avg, COUNT(r.$m) AS {$m}_n";
    }
    $sql = "SELECT " . implode(', ', $selects) . ",
                   COUNT(DISTINCT r.sensor_id) AS sensor_count,
                   COUNT(*) AS reading_count,
                   MIN(r.recorded_at) AS first_at, MAX(r.recorded_at) AS last_at
            FROM readings r
            JOIN sensors s ON r.sensor_id = s.id
            WHERE " . implode(' AND ', $where);
    $stmt = db()->prepare($sql);
    $stmt->execute($params);
    $row = $stmt->fetch() ?: [];

    $out = [];
    foreach ($metrics as $m) {
        $n = (int)($row["{$m}_n"] ?? 0);
        $out[$m] = [
            'avg'   => ($n > 0 && $row["{$m}_avg"] !== null) ? round((float)$row["{$m}_avg"], 2) : null,
            'count' => $n,
        ];
    }
    jsonResponse([
        'period'        => $period,
        'region'        => ($region === '' || $region === 'ALL') ? 'all' : $region,
        'location'      => in_array($location, ['indoor', 'outdoor'], true) ? $location : 'all',
        'sensor_count'  => (int)($row['sensor_count'] ?? 0),
        'reading_count' => (int)($row['reading_count'] ?? 0),
        'first_at'      => toIsoUtc($row['first_at'] ?? null),
        'last_at'       => toIsoUtc($row['last_at'] ?? null),
        'metrics'       => $out,
    ]);
}

// ─────────────────────────────────────────────────────────
// GET reading — a sensor sends data
//
// Privalomi parametrai: lat, lng
// At least one metric parameter: temperature, humidity, ...
//
// URL pavyzdys:
//   /api/sensors.php?action=reading
//     &lat=54.6872000&lng=25.2797000
//     &temperature=21.3&humidity=55.1&co2=412
// ─────────────────────────────────────────────────────────
if ($action === 'reading') {
    $lat = getFloat('lat', -90,  90);
    $lng = getFloat('lng', -180, 180);
    $mac = getMac('mac');

    if ($lat === null || $lng === null || $mac === '') {
        jsonResponse([
            'error' => 'lat, lng ir mac privalomi',
            'pvz'   => '?action=reading&lat=54.6872000&lng=25.2797000&mac=AA:BB:CC:DD:EE:FF&temperature=21.3&humidity=55.1'
        ], 400);
    }

    // 1.4 Rate limiting: a sensor must send no more than once per 5 min.
    // Keyed by MAC (more precise than IP, since several sensors may be behind NAT).
    // Allow up to 2 requests per 5-min window (margin for retransmissions).
    if (!rateLimitOk('read:' . $mac, 2, 300)) {
        jsonResponse([
            'error' => 'Per dažnai. Jutiklis turi siųsti ne dažniau kaip kartą per 5 minutes.',
            'code'  => 'rate_limited',
        ], 429);
    }

    // 1. Exact match: a sensor with this lat+lng+mac is already confirmed.
    $stmt = db()->prepare(
        "SELECT id, secret FROM sensors WHERE lat = :lat AND lng = :lng AND mac = :mac"
    );
    $stmt->execute([':lat' => $lat, ':lng' => $lng, ':mac' => $mac]);
    $sensor = $stmt->fetch();

    if ($sensor) {
        $sensorId = (int)$sensor['id'];

        // 1.3 HMAC signature verification (optional).
        // If the sensor has a `secret`, the request MUST include a valid
        // `sig` parameter = HMAC-SHA256(lat|lng|mac, secret). Protects against
        // forged readings even if the coordinates and MAC are known.
        //
        // IMPORTANT: the signature uses the RAW GET values, exactly as
        // sent by the sensor (e.g. "54.6872000"), NOT a processed float,
        // so the signature matches the firmware (String(lat, 7)). The MAC is normalized
        // to uppercase with colons on both sides.
        if (!empty($sensor['secret'])) {
            $sig = $_GET['sig'] ?? $_POST['sig'] ?? '';
            $rawLat = trim((string)($_GET['lat'] ?? $_POST['lat'] ?? ''));
            $rawLng = trim((string)($_GET['lng'] ?? $_POST['lng'] ?? ''));
            $payload = $rawLat . '|' . $rawLng . '|' . $mac;
            $expected = hash_hmac('sha256', $payload, $sensor['secret']);
            if (!is_string($sig) || !hash_equals($expected, strtolower($sig))) {
                jsonResponse([
                    'error' => 'Neteisingas arba trūkstamas parašas (sig).',
                    'code'  => 'invalid_signature',
                ], 401);
            }
        }
    } else {
        // 2. No exact match — look for a PENDING (mac IS NULL)
        //    record at those coordinates. The first send "claims" the MAC.
        $pendStmt = db()->prepare(
            "SELECT id FROM sensors
             WHERE lat = :lat AND lng = :lng AND mac IS NULL
             ORDER BY registered_at ASC, id ASC
             LIMIT 1"
        );
        $pendStmt->execute([':lat' => $lat, ':lng' => $lng]);
        $pending = $pendStmt->fetch();

        if (!$pending) {
            // Neither an exact sensor nor a pending record exists
            jsonResponse([
                'error' => 'Jutiklis neužregistruotas. Pirmiau užregistruokite per ?action=register',
                'lat'   => $lat,
                'lng'   => $lng,
                'mac'   => $mac,
            ], 403);
        }

        // Assign the MAC to the pending record (claim the registration)
        // and immediately CONFIRM the sensor (confirmed = 1).
        $sensorId = (int)$pending['id'];
        try {
            db()->prepare("UPDATE sensors SET mac = :mac, confirmed = 1 WHERE id = :id")
               ->execute([':mac' => $mac, ':id' => $sensorId]);
        } catch (PDOException $e) {
            // If the same MAC is already assigned to another record at those coordinates
            jsonResponse([
                'error' => 'Šis MAC jau priskirtas jutikliui tose koordinatėse.',
                'mac'   => $mac,
            ], 409);
        }
    }

    // $sensorId is already set in both branches (exact match or pending).
    // Atnaujinti last_seen

    // Collect metric fields from GET parameters
    $allowed = ['temperature','humidity','co2','pm1','pm2_5','pm10','grains','radiation',
                'alcohol','methane','propane','butane','lpg','hydrogen','co','smoke',
                'ammonia','nox','benzene','air_quality','co2_equiv'];
    $fields  = [];
    $params  = [':sensor_id' => $sensorId];

    foreach ($allowed as $field) {
        if (isset($_GET[$field]) && $_GET[$field] !== '' && is_numeric($_GET[$field])) {
            $fields[]          = $field;
            $params[":$field"] = (float)$_GET[$field];
        }
    }

    if (empty($fields)) {
        jsonResponse([
            'error'   => 'Nėra tinkamų matavimo laukų',
            'galimi'  => $allowed,
            'pvz'     => '&temperature=21.3&humidity=55.1',
        ], 400);
    }

    // Optional device timestamp (UTC) for accurate time correlation. The sensor
    // may send recorded_at as ISO 8601 UTC ("…Z") or a Unix epoch (seconds).
    // Validated to a sane window (≤30 d old, ≤5 min in the future for clock skew);
    // otherwise the column DEFAULT (server time, UTC) is used.
    $recordedAt = null;
    $tsRaw = trim((string)($_GET['recorded_at'] ?? $_GET['ts'] ?? ''));
    if ($tsRaw !== '') {
        $ts = ctype_digit($tsRaw) ? (int)$tsRaw : strtotime($tsRaw);
        if ($ts !== false && $ts > 0) {
            $now = time();
            if ($ts >= $now - 2592000 && $ts <= $now + 300) {
                $recordedAt = gmdate('Y-m-d H:i:s', $ts);
            }
        }
    }

    $cols = implode(', ', $fields);
    $vals = implode(', ', array_map(fn($f) => ":$f", $fields));
    if ($recordedAt !== null) {
        $cols .= ', recorded_at';
        $vals .= ', :recorded_at';
        $params[':recorded_at'] = $recordedAt;
    }

    db()->prepare("INSERT INTO readings (sensor_id, $cols) VALUES (:sensor_id, $vals)")
       ->execute($params);
    $readingId = (int)db()->lastInsertId();

    // Update last_seen and confirmed=1 (first successful record)
    db()->prepare("
        UPDATE sensors
        SET last_seen = NOW(),
            confirmed = 1
        WHERE id = :id
    ")->execute([':id' => $sensorId]);

    jsonResponse([
        'ok'         => true,
        'sensor_id'  => $sensorId,
        'reading_id' => $readingId,
        'stored'     => $fields,
    ]);
}

// ─────────────────────────────────────────────────────────
// GET register — register a new sensor by coordinates
//
// Called from the index.php form or directly.
// Creates a record with confirmed=0.
// Within 3 min it must receive ?action=reading, otherwise it is deleted.
//
// URL: /api/sensors.php?action=register&lat=54.6872000&lng=25.2797000
// ─────────────────────────────────────────────────────────
if ($action === 'register') {
    $lat = getFloat('lat', -90,  90);
    $lng = getFloat('lng', -180, 180);
    $force = isset($_GET['force']) && $_GET['force'] === '1';
    // Indoor (0, default) or outdoor (1) sensor.
    // If the field is not provided — indoor by default (0).
    $isOutdoor = (isset($_GET['is_outdoor']) && ($_GET['is_outdoor'] === '1' || $_GET['is_outdoor'] === 'true')) ? 1 : 0;

    if ($lat === null || $lng === null) {
        jsonResponse([
            'error' => 'lat ir lng privalomi (7 dešimtainių ženklų tikslumas)',
            'pvz'   => '?action=register&lat=54.6872000&lng=25.2797000',
        ], 400);
    }

    // Is there already a sensor at these coordinates (confirmed or pending)?
    $existsStmt = db()->prepare(
        "SELECT COUNT(*) FROM sensors WHERE lat = :lat AND lng = :lng"
    );
    $existsStmt->execute([':lat' => $lat, ':lng' => $lng]);
    $coordsExist = (int)$existsStmt->fetchColumn() > 0;

    // If the coordinates are taken and the user has not confirmed — ask.
    if ($coordsExist && !$force) {
        jsonResponse([
            'ok'                 => false,
            'needs_confirmation' => true,
            'message'            => 'Šiose koordinatėse jau yra jutiklis. Registruoti naują toje pačioje vietoje?',
            'lat'                => $lat,
            'lng'                => $lng,
        ], 200);
    }

    try {
        // The prefix is chosen automatically by the nearest city
        $city = nearestCity($lat, $lng);

        // Pending sensor: mac = NULL (the MAC will be claimed on the first
        // at data-send time). Several NULLs at the same location
        // sugyvena unikaliame rakte.
        $stmt = db()->prepare(
            "INSERT INTO sensors (lat, lng, mac, is_outdoor, city_prefix) VALUES (:lat, :lng, NULL, :outdoor, :prefix)"
        );
        $stmt->execute([':lat' => $lat, ':lng' => $lng, ':outdoor' => $isOutdoor, ':prefix' => $city['prefix']]);
        $id = (int)db()->lastInsertId();

        // Sequence number within the city (not the DB id):
        // how many sensors of this prefix have id <= the new one
        $seqStmt = db()->prepare(
            "SELECT COUNT(*) FROM sensors WHERE city_prefix = :p AND id <= :id"
        );
        $seqStmt->execute([':p' => $city['prefix'], ':id' => $id]);
        $seq   = (int)$seqStmt->fetchColumn();
        $label = $city['prefix'] . $seq;

        jsonResponse([
            'ok'        => true,
            'sensor_id' => $id,
            'label'     => $label,
            'city'      => $city['city'],
            'distance_km' => $city['distance_km'],
            'geo_source'  => $city['source'] ?? 'local',
            'warning'     => $city['geo_error'] ?? null,
            'confirmed' => false,
            'info'      => 'Jutiklis laukia patvirtinimo. Per 3 min siųskite ?action=reading su šiomis koordinatėmis.',
            'reading_url' => "?action=reading&lat={$lat}&lng={$lng}&temperature=XX&humidity=XX",
        ], 201);

    } catch (PDOException $e) {
        // 23000 can mean TWO things:
        //  (a) a real duplicate (lat+lng+mac already exists) — only for confirmed ones;
        //  (b) sena schema su `mac NOT NULL` — INSERT NULL meta „cannot be null".
        // We distinguish by the error text.
        $msg = $e->getMessage();
        if (stripos($msg, 'cannot be null') !== false || stripos($msg, '1048') !== false) {
            jsonResponse([
                'error' => 'Sena duomenų bazės schema: stulpelis `mac` yra NOT NULL. '
                         . 'Atnaujinkite schemą per admin.php (Jutiklių valdymas → schemos atnaujinimas) '
                         . 'arba įvykdykite: ALTER TABLE sensors MODIFY mac VARCHAR(17) NULL DEFAULT NULL;',
                'code'  => 'schema_outdated',
            ], 500);
        }
        if ($e->getCode() === '23000') {
            // A real duplicate (same lat+lng+mac). With mac=NULL this should not
            // happen (NULL allows several), so we reach here only for a confirmed MAC.
            $existing = db()->prepare(
                "SELECT id, CONCAT(city_prefix, (
                    SELECT COUNT(*) FROM sensors s2
                    WHERE s2.city_prefix = sensors.city_prefix AND s2.id <= sensors.id
                 )) AS label, confirmed
                 FROM sensors WHERE lat = :lat AND lng = :lng"
            );
            $existing->execute([':lat' => $lat, ':lng' => $lng]);
            $row = $existing->fetch();
            jsonResponse([
                'error'     => 'Jutiklis su šiomis koordinatėmis jau užregistruotas',
                'sensor_id' => (int)$row['id'],
                'label'     => $row['label'],
                'confirmed' => (bool)$row['confirmed'],
            ], 409);
        }
        throw $e;
    }
}

