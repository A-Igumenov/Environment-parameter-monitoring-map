/**
 * 5.4 Sends the error to ERROR_WEBHOOK_URL (Sentry/Slack/Discord etc.).
 * Short timeout so it does not block the response; errors here are ignored.
 */
function reportError(Throwable $e): void {
    $payload = json_encode([
        'message'   => $e->getMessage(),
        'file'      => $e->getFile() . ':' . $e->getLine(),
        'timestamp' => date('c'),
        'url'       => $_SERVER['REQUEST_URI'] ?? '',
    ], JSON_UNESCAPED_UNICODE);
    $ctx = stream_context_create([
        'http' => [
            'method'  => 'POST',
            'header'  => "Content-Type: application/json\r\n",
            'content' => $payload,
            'timeout' => 2,
        ],
    ]);
    @file_get_contents(ERROR_WEBHOOK_URL, false, $ctx);
}

