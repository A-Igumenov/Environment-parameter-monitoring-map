// ─────────────────────────────────────────────────────────
// Helper: float from GET, null if missing/invalid
// ─────────────────────────────────────────────────────────
function getFloat(string $key, float $min, float $max): ?float {
    if (!isset($_GET[$key]) || $_GET[$key] === '') return null;
    $v = filter_var($_GET[$key], FILTER_VALIDATE_FLOAT);
    if ($v === false || $v < $min || $v > $max) return null;
    return round($v, 7);
}

// MAC address validation and normalization.
// Accepts AA:BB:CC:DD:EE:FF, AA-BB-..., aabbcc... → returns uppercase
// with colons, or '' if invalid/not provided.
function getMac(string $key = 'mac'): string {
    $raw = $_GET[$key] ?? '';
    if ($raw === '') return '';
    // Remove separators, keep only hex
    $hex = preg_replace('/[^0-9A-Fa-f]/', '', $raw);
    if (strlen($hex) !== 12) return ''; // invalid → empty
    $hex = strtoupper($hex);
    return implode(':', str_split($hex, 2)); // AA:BB:CC:DD:EE:FF
}

/**
 * 1.4 Rate limiting (slankiojantis fiksuotas langas, DB pagrindu).
 * Returns true if the request is ALLOWED, false if the limit is exceeded.
 * $key — a unique key (e.g. "read:1.2.3.4"); $max — max requests
 * per $windowSec-second window. Concurrency-safe (INSERT ... ON
 * DUPLICATE KEY UPDATE atomically increments the counter).
 */
function rateLimitOk(string $key, int $max, int $windowSec): bool {
    try {
        $now = time();
        $windowStart = $now - ($now % $windowSec); // window start
        $stmt = db()->prepare(
            "INSERT INTO rate_limits (rl_key, window_start, counter)
             VALUES (:k, :ws, 1)
             ON DUPLICATE KEY UPDATE
                counter = IF(window_start = :ws2, counter + 1, 1),
                window_start = IF(window_start = :ws3, window_start, :ws4)"
        );
        $stmt->execute([
            ':k' => $key, ':ws' => $windowStart,
            ':ws2' => $windowStart, ':ws3' => $windowStart, ':ws4' => $windowStart,
        ]);
        // Read the current counter
        $check = db()->prepare("SELECT counter FROM rate_limits WHERE rl_key = :k");
        $check->execute([':k' => $key]);
        $count = (int)$check->fetchColumn();
        return $count <= $max;
    } catch (PDOException) {
        // If the table is missing (old schema) — do not block
        return true;
    }
}

